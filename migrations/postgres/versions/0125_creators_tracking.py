"""Creators, delivery 1: the creators a brand follows, and the history of every paid read
of a public account (m-24946121, m-24946127; epic m-24880379; ADR 45)

Revision ID: 0125
Revises: 0124
Create Date: 2026-11-04

Design: `docs/diseno-modulo-creadores.md` §4, §5 and §7. A business follows Instagram
creators (`tracked_creators`, per brand, RLS); each «Actualizar» reads the creator's
profile and latest 48 reels through the metered gate and keeps that read as one
`creator_snapshots` row plus one `public_reel_reads` row per reel. The read is public data
shared by every business (a second business following the same creator the same day pays
nothing), so the history tables are global.

## Global tables — public data, NO `tenant_id`, NO RLS (rule of 0023, 0036, 0117)

- `creator_snapshots` — one row per read of an account: the profile figures, how many
  reels and pages it read, the stretch of time it covers, the credits it cost (a number,
  with no owner) and its provenance (`profile_payload_id` + `profile_payload_fetched_at`
  → `vendor_payloads`, `parser_version`). `UNIQUE (network, handle, read_at)`. Its `id` is
  generated by the service before the first paid call, so the per-call usage keys
  (`creators:<snapshot_id>:…`) exist before the row does.
- `public_reel_reads` — one row per reel in a read: only what changes between reads (the
  counters), with the page it was parsed from (`source_payload_id` +
  `source_payload_fetched_at`). Duration, caption, audio, collaborations and sponsorship
  live once in `public_reels`. Joined to `public_reels` on `(network, reel_id)` without an
  FK (pattern of 0119).
- `public_reels` gains `coauthors` (handles of the other accounts on the reel; NULL = not
  read, `[]` = none), `sound_id`, `sound_is_original` and `counts_hidden` (the account hid
  views and likes — «hidden», not «missing»). `is_paid_partnership` already exists (0117)
  and is filled from parser version 2 on.

**0117's rule extends to both new tables:** no global table may ever gain a column naming
a tenant, a brand or a user, nor record who asked for, followed or looked at an account.
`test_creators_tracking_db.py` pins it structurally. Both are append-only for
`qualify_app` (SELECT, INSERT): a read is history, never rewritten.

## Per-tenant table — `tenant_id NOT NULL` + RLS ENABLE + FORCE + the NULLIF policy

- `tracked_creators` — a creator a brand follows. `UNIQUE (brand_id, network, handle)` is
  the idempotency key of «Agregar» (`ON CONFLICT DO UPDATE` reactivates an archived one).
  Composite FK `(brand_id, tenant_id) → brands (id, tenant_id)` (`uq_ads_brand_tenant`,
  0114) and `UNIQUE (id, tenant_id, brand_id)` as the target of delivery 2's children.
  `last_snapshot_id` points from this per-tenant table to the global history (never the
  other way round). No DELETE grant: «Quitar de la lista» archives.

## `vendor_usage_events` — two new features

`ck_vendor_usage_feature` (widened to seven features by 0124, ADR 42 R5) gains
`creator_profile` and `creator_reels`: the metered gate books every Creators call under
them, so the module's own budget (50 credits a day, 300 a month) sums apart from the rest
of the business's 150/600 (`usage.store().spent(features=...)`).

## Downgrade

Drops `tracked_creators`, `public_reel_reads`, `creator_snapshots` and the four
`public_reels` columns, and puts back 0124's seven-feature CHECK — `NOT VALID`, like
0124's own downgrade: the `creator_profile` / `creator_reels` usage rows are kept (they
still count against the business's cap) and only new rows are checked. The read history
is lost, and it cannot be bought again: the vendor sells no history.
"""

from __future__ import annotations

import sqlalchemy as sa
from alembic import op
from sqlalchemy.dialects.postgresql import JSONB
from sqlalchemy.dialects.postgresql import UUID as PGUUID

revision = "0125"
down_revision = "0124"
branch_labels = None
depends_on = None

# The same normalization as `creators` (0036) and `public_reels` (0117).
_HANDLE_CHECK = "handle <> '' AND handle = lower(handle) AND left(handle, 1) <> '@'"
_NETWORK_CHECK = "network IN ('tiktok','instagram')"
# 0124's seven (ADR 42 R5), and the two of the Creators module.
_SEVEN = (
    "'reels_list','reels_transcript','avatar_refresh','profile',"
    "'posts','referentes_search','trending'"
)
_NINE = f"{_SEVEN},'creator_profile','creator_reels'"
_FEATURE_CHECK = "ck_vendor_usage_feature"


def _id() -> sa.Column:
    return sa.Column(
        "id", PGUUID(as_uuid=True), server_default=sa.text("gen_random_uuid()"), primary_key=True
    )


def _now(name: str) -> sa.Column:
    return sa.Column(
        name, sa.DateTime(timezone=True), server_default=sa.text("now()"), nullable=False
    )


def _ts(name: str) -> sa.Column:
    return sa.Column(name, sa.DateTime(timezone=True), nullable=True)


def _text(name: str) -> sa.Column:
    return sa.Column(name, sa.Text(), server_default="", nullable=False)


def _payload_fk(name: str) -> sa.Column:
    return sa.Column(
        name,
        PGUUID(as_uuid=True),
        sa.ForeignKey("vendor_payloads.id", ondelete="SET NULL"),
        nullable=True,
    )


def _public_reels_columns() -> None:
    op.add_column("public_reels", sa.Column("coauthors", JSONB(), nullable=True))
    op.add_column("public_reels", sa.Column("sound_id", sa.Text(), nullable=True))
    op.add_column("public_reels", sa.Column("sound_is_original", sa.Boolean(), nullable=True))
    op.add_column(
        "public_reels",
        sa.Column("counts_hidden", sa.Boolean(), server_default=sa.text("false"), nullable=False),
    )
    op.create_check_constraint(
        "ck_public_reel_coauthors",
        "public_reels",
        "coauthors IS NULL OR jsonb_typeof(coauthors) = 'array'",
    )


def _history_tables() -> None:
    op.create_table(
        "creator_snapshots",
        # No server default on purpose: the service generates it before paying.
        sa.Column("id", PGUUID(as_uuid=True), primary_key=True),
        sa.Column("network", sa.Text(), nullable=False),
        sa.Column("handle", sa.Text(), nullable=False),
        sa.Column("read_at", sa.DateTime(timezone=True), nullable=False),
        sa.Column("status", sa.Text(), nullable=False),
        sa.Column("followers", sa.BigInteger(), nullable=True),
        sa.Column("following", sa.BigInteger(), nullable=True),
        sa.Column("posts_count", sa.BigInteger(), nullable=True),
        _text("full_name"),
        _text("bio"),
        _text("category"),
        _text("external_url"),
        _text("avatar_url"),
        sa.Column("is_verified", sa.Boolean(), server_default=sa.text("false"), nullable=False),
        sa.Column("is_private", sa.Boolean(), server_default=sa.text("false"), nullable=False),
        sa.Column("reels_target", sa.Integer(), nullable=False),
        sa.Column("reels_read", sa.Integer(), server_default="0", nullable=False),
        sa.Column("pages_read", sa.Integer(), server_default="0", nullable=False),
        _ts("oldest_taken_at"),
        _ts("newest_taken_at"),
        sa.Column("credits", sa.Integer(), server_default="0", nullable=False),
        _payload_fk("profile_payload_id"),
        _ts("profile_payload_fetched_at"),
        sa.Column("parser_version", sa.Integer(), nullable=False),
        _now("created_at"),
        sa.UniqueConstraint("network", "handle", "read_at", name="uq_creator_snapshot"),
        sa.CheckConstraint(_NETWORK_CHECK, name="ck_creator_snapshot_network"),
        sa.CheckConstraint(_HANDLE_CHECK, name="ck_creator_snapshot_handle_normalized"),
        sa.CheckConstraint(
            "status IN ('ok','partial','private','missing','error')",
            name="ck_creator_snapshot_status",
        ),
        sa.CheckConstraint(
            "reels_target >= 0 AND reels_read >= 0 AND pages_read >= 0 AND credits >= 0",
            name="ck_creator_snapshot_counters",
        ),
        sa.CheckConstraint("parser_version > 0", name="ck_creator_snapshot_parser_version"),
        sa.CheckConstraint(
            "profile_payload_id IS NULL OR profile_payload_fetched_at IS NOT NULL",
            name="ck_creator_snapshot_payload",
        ),
    )
    # «The latest read of an account» — the 24 h freshness check and the sheet.
    op.execute(
        "CREATE INDEX ix_creator_snapshots_latest "
        "ON creator_snapshots (network, handle, read_at DESC);"
    )
    op.create_index(
        "ix_creator_snapshots_payload",
        "creator_snapshots",
        ["profile_payload_id"],
        postgresql_where=sa.text("profile_payload_id IS NOT NULL"),
    )
    op.execute("GRANT SELECT, INSERT ON creator_snapshots TO qualify_app;")
    op.execute("GRANT SELECT ON creator_snapshots TO qualify_admin;")

    op.create_table(
        "public_reel_reads",
        sa.Column(
            "snapshot_id",
            PGUUID(as_uuid=True),
            sa.ForeignKey("creator_snapshots.id", ondelete="CASCADE"),
            nullable=False,
        ),
        sa.Column("network", sa.Text(), nullable=False),
        sa.Column("reel_id", sa.Text(), nullable=False),
        sa.Column("position", sa.Integer(), nullable=False),
        sa.Column("taken_at", sa.DateTime(timezone=True), nullable=False),
        # NULL = the vendor did not send it or the account hid it — never "zero".
        *(
            sa.Column(name, sa.BigInteger(), nullable=True)
            for name in ("views", "likes", "comments", "saves", "shares")
        ),
        _payload_fk("source_payload_id"),
        _ts("source_payload_fetched_at"),
        sa.Column("parser_version", sa.Integer(), nullable=False),
        sa.PrimaryKeyConstraint("snapshot_id", "reel_id", name="pk_public_reel_reads"),
        sa.CheckConstraint(_NETWORK_CHECK, name="ck_public_reel_read_network"),
        sa.CheckConstraint("reel_id <> '' AND position > 0", name="ck_public_reel_read_values"),
        sa.CheckConstraint("parser_version > 0", name="ck_public_reel_read_parser_version"),
        sa.CheckConstraint(
            "source_payload_id IS NULL OR source_payload_fetched_at IS NOT NULL",
            name="ck_public_reel_read_source_payload",
        ),
    )
    # The curve of one reel across reads.
    op.create_index(
        "ix_public_reel_reads_reel", "public_reel_reads", ["network", "reel_id", "snapshot_id"]
    )
    op.create_index(
        "ix_public_reel_reads_payload",
        "public_reel_reads",
        ["source_payload_id"],
        postgresql_where=sa.text("source_payload_id IS NOT NULL"),
    )
    op.execute("GRANT SELECT, INSERT ON public_reel_reads TO qualify_app;")
    op.execute("GRANT SELECT ON public_reel_reads TO qualify_admin;")


def _tracked_creators() -> None:
    op.create_table(
        "tracked_creators",
        _id(),
        sa.Column(
            "tenant_id",
            PGUUID(as_uuid=True),
            sa.ForeignKey("tenants.id", ondelete="CASCADE"),
            nullable=False,
        ),
        sa.Column("brand_id", PGUUID(as_uuid=True), nullable=False),
        sa.Column("network", sa.Text(), nullable=False),
        sa.Column("handle", sa.Text(), nullable=False),
        _text("note"),
        sa.Column("status", sa.Text(), server_default="active", nullable=False),
        sa.Column(
            "last_snapshot_id",
            PGUUID(as_uuid=True),
            sa.ForeignKey("creator_snapshots.id", ondelete="SET NULL"),
            nullable=True,
        ),
        sa.Column("refresh_state", sa.Text(), server_default="never", nullable=False),
        sa.Column("refresh_error", sa.Text(), nullable=True),
        _ts("refresh_started_at"),
        sa.Column(
            "added_by_user_id",
            PGUUID(as_uuid=True),
            sa.ForeignKey("users.id", ondelete="SET NULL"),
            nullable=True,
        ),
        _now("created_at"),
        _now("updated_at"),
        _ts("archived_at"),
        sa.ForeignKeyConstraint(
            ["brand_id", "tenant_id"],
            ["brands.id", "brands.tenant_id"],
            name="fk_tracked_creator_brand",
            ondelete="CASCADE",
        ),
        sa.UniqueConstraint("brand_id", "network", "handle", name="uq_tracked_creator"),
        # Target of delivery 2's composite FKs: a candidate never hangs on another brand.
        sa.UniqueConstraint("id", "tenant_id", "brand_id", name="uq_tracked_creator_owner"),
        sa.CheckConstraint(_NETWORK_CHECK, name="ck_tracked_creator_network"),
        sa.CheckConstraint(_HANDLE_CHECK, name="ck_tracked_creator_handle_normalized"),
        sa.CheckConstraint("status IN ('active','archived')", name="ck_tracked_creator_status"),
        sa.CheckConstraint(
            "refresh_state IN ('never','reading','ok','failed')",
            name="ck_tracked_creator_refresh_state",
        ),
        sa.CheckConstraint(
            "(status = 'archived') = (archived_at IS NOT NULL)",
            name="ck_tracked_creator_archived",
        ),
    )
    op.create_index("ix_tracked_creators_tenant", "tracked_creators", ["tenant_id"])
    op.create_index("ix_tracked_creators_brand", "tracked_creators", ["brand_id", "status"])
    op.create_index(
        "ix_tracked_creators_snapshot",
        "tracked_creators",
        ["last_snapshot_id"],
        postgresql_where=sa.text("last_snapshot_id IS NOT NULL"),
    )
    op.create_index(
        "ix_tracked_creators_user",
        "tracked_creators",
        ["added_by_user_id"],
        postgresql_where=sa.text("added_by_user_id IS NOT NULL"),
    )
    op.execute("GRANT SELECT, INSERT, UPDATE ON tracked_creators TO qualify_app;")
    op.execute("GRANT SELECT ON tracked_creators TO qualify_admin;")
    op.execute("ALTER TABLE tracked_creators ENABLE ROW LEVEL SECURITY;")
    op.execute("ALTER TABLE tracked_creators FORCE ROW LEVEL SECURITY;")
    op.execute(
        """
        CREATE POLICY tenant_isolation ON tracked_creators
            USING (tenant_id = NULLIF(current_setting('app.tenant_id', true), '')::uuid)
            WITH CHECK (tenant_id = NULLIF(current_setting('app.tenant_id', true), '')::uuid);
        """
    )


def _widen_usage_features() -> None:
    op.drop_constraint(_FEATURE_CHECK, "vendor_usage_events", type_="check")
    op.create_check_constraint(_FEATURE_CHECK, "vendor_usage_events", f"feature IN ({_NINE})")


def _restore_usage_features() -> None:
    # 0124's own downgrade pattern: keep the rows, check only new ones.
    op.drop_constraint(_FEATURE_CHECK, "vendor_usage_events", type_="check")
    op.execute(
        f"ALTER TABLE vendor_usage_events ADD CONSTRAINT {_FEATURE_CHECK} "
        f"CHECK (feature IN ({_SEVEN})) NOT VALID"
    )


def upgrade() -> None:
    _public_reels_columns()
    _history_tables()
    _tracked_creators()
    _widen_usage_features()


def downgrade() -> None:
    _restore_usage_features()
    op.drop_table("tracked_creators")
    op.drop_table("public_reel_reads")
    op.drop_table("creator_snapshots")
    op.drop_constraint("ck_public_reel_coauthors", "public_reels", type_="check")
    for column in ("counts_hidden", "sound_is_original", "sound_id", "coauthors"):
        op.drop_column("public_reels", column)
