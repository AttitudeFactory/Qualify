def seedance_family(model_id: str) -> SeedanceFamily:
    """The family of a model id, dated (`seedance-1-0-pro-250528` → `seedance-1-0-pro`)
    or not (`dreamina-seedance-2-0`). The id itself is tried first, and only a six-digit
    `YYMMDD` suffix is taken for a date — a 2.x id ends in its version digit, which is
    not one. An unknown family raises — a model we have not read the limits of is not
    guessed."""
    if model_id in SEEDANCE_FAMILIES:
        return SEEDANCE_FAMILIES[model_id]
    base, _, suffix = model_id.rpartition("-")
    key = base if suffix.isdigit() and len(suffix) == 6 else model_id
    try:
        return SEEDANCE_FAMILIES[key]
    except KeyError:
        raise ValueError(
            f"unknown Seedance model {model_id!r}; known families: {sorted(SEEDANCE_FAMILIES)}"
        ) from None


def parse_endpoints(raw: str | None) -> dict[str, str]:
    """``"model=ep-…,model=ep-…"`` (the ``QUALIFY_BYTEPLUS_ARK_ENDPOINTS`` value) as a map.
    Empty → no endpoints. A malformed entry raises at wiring rather than turning into a
    refused generation later."""
    endpoints: dict[str, str] = {}
    for entry in (raw or "").split(","):
        entry = entry.strip()
        if not entry:
            continue
        model, sep, endpoint = (part.strip() for part in entry.partition("="))
        if not sep or not model or not endpoint:
            raise ValueError(f"ModelArk endpoint entry {entry!r} is not 'model=ep-…'")
        if model in endpoints:
            raise ValueError(f"ModelArk endpoint for {model!r} is given twice")
        endpoints[model] = endpoint
    return endpoints


def output_dimensions(model_id: str, resolution: str, ratio: str) -> tuple[int, int]:
    """The width × height `model_id` renders at `resolution` and `ratio`."""
    return _DIMS[seedance_family(model_id).dims][resolution][ratio]


def estimate_video_tokens(model_id: str, resolution: str, ratio: str, seconds: int) -> int:
    """`width × height × 24 × seconds / 1024` at the output size (ModelArk's own formula —
    the real count comes back in `usage.completion_tokens`)."""
    width, height = output_dimensions(model_id, resolution, ratio)
    return round(width * height * FPS * seconds / 1024)


def video_cost_usd(pricing: PricingTable, model_id: str, resolution: str, tokens: int) -> Decimal:
    """What `tokens` of video cost on `model_id` at `resolution` (per-million-token rate)."""
    rate = pricing.unit_price(model_id=model_id, unit=f"per_mtok_video_{resolution}")
    return (Decimal(tokens) * rate / Decimal(1_000_000)).quantize(Decimal("0.000001"))


