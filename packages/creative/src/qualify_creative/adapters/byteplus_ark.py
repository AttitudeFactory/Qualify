class ArkError(Exception):
    """Base for everything these adapters raise, so the router's hop record names it."""


class ArkAPIError(ArkError):
    """A non-2xx answer, with ModelArk's own error code kept for branching."""

    def __init__(self, status_code: int, code: str | None, message: str) -> None:
        super().__init__(f"HTTP {status_code} {code or 'unknown_error'}: {message}")
        self.status_code = status_code
        self.code = code


class ArkPresetRefused(ArkError):
    """The request would reach ModelArk by bare model id — the campaign-authorized preset —
    because no custom endpoint is configured for that model. Raised before any network
    call; nothing was sent."""

    def __init__(self, model_id: str) -> None:
        super().__init__(
            f"ModelArk preset refused: no custom endpoint (ep-…) configured for {model_id!r}; "
            "set it in QUALIFY_BYTEPLUS_ARK_ENDPOINTS — the bare model id reaches the "
            "data-collection preset"
        )
        self.model_id = model_id


class ArkTaskFailed(ArkError):
    """The video task ended `failed`/`cancelled`/`expired` — not billed."""

    def __init__(self, task_id: str, status: str, code: str | None, message: str | None) -> None:
        super().__init__(f"Seedance task {task_id} {status}: {code or 'unknown'}: {message or ''}")
        self.task_id = task_id
        self.status = status
        self.code = code


class ArkTaskTimeout(ArkError):
    """The poll window closed before the task finished. The task keeps running (and is
    billed if it succeeds): its id is kept for the support ticket."""

    def __init__(self, task_id: str, waited_seconds: float) -> None:
        super().__init__(
            f"Seedance task {task_id} still running after {waited_seconds:.0f}s; "
            "it will keep generating — recover it by task id"
        )
        self.task_id = task_id


