class ArkError(Exception):
    """Base for everything these adapters raise, so the router's hop record names it."""


class ArkAPIError(ArkError):
    """A non-2xx answer, with ModelArk's own error code kept for branching."""

    def __init__(self, status_code: int, code: str | None, message: str) -> None:
        super().__init__(f"HTTP {status_code} {code or 'unknown_error'}: {message}")
        self.status_code = status_code
        self.code = code


class VendorBusy(ArkAPIError):
    """ModelArk is busy, not broken (`BUSY_CODES`, or any 429): nothing was created and
    nothing is billed. `retry_after_seconds` is the suggested wait — the vendor's own
    `Retry-After` when it sent one. A subclass of `ArkAPIError`, so code that branches on
    the HTTP status (and the operator's message, matched on «HTTP 429») is unchanged."""

    def __init__(
        self, status_code: int, code: str | None, message: str, retry_after_seconds: float
    ) -> None:
        super().__init__(status_code, code, message)
        self.retry_after_seconds = retry_after_seconds


class ArkTaskFailed(ArkError):
    """The video task ended `failed`/`cancelled`/`expired` — not billed."""

    def __init__(self, task_id: str, status: str, code: str | None, message: str | None) -> None:
        super().__init__(f"Seedance task {task_id} {status}: {code or 'unknown'}: {message or ''}")
        self.task_id = task_id
        self.status = status
        self.code = code


class ArkTaskTimeout(ArkError):
    """This thread stopped waiting before the task finished — still queued past
    `queue_timeout_seconds`, or running past the render window. The task keeps going
    (and is billed if it succeeds): the caller, which heard its id at creation
    (`VendorTaskObserver.created`), resumes it by id (`RESUME_TASK_PARAM`)."""

    def __init__(self, task_id: str, waited_seconds: float, status: str = "") -> None:
        super().__init__(
            f"Seedance task {task_id} still {status or 'running'} after {waited_seconds:.0f}s; "
            "it will keep generating — recover it by task id"
        )
        self.task_id = task_id
        self.status = status


