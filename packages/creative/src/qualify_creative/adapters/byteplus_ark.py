class SeedreamImageAdapter(_ArkClient):
    """``GenerationProvider`` for a generated image (`GenerationTask.PRODUCT_IMAGE`) —
    the advertising image's scene, or a video's first frame.

    ``request.params``: ``prompt`` (required); ``images`` — reference images (URLs or
    ``data:`` URLs, ≤14) the scene must keep recognisable; ``size`` — ``"WxH"`` within the
    model's pixel range, or a level (``"2K"``); ``model`` (default: the adapter's).
    The image comes back as bytes (``payload["images"]``), never as a 24 h URL.
    """

    name = "seedream"
    supports = frozenset({GenerationTask.PRODUCT_IMAGE})

    def __init__(
        self,
        *,
        model: str = DEFAULT_SEEDREAM_MODEL,
        base_url: str = BASE_URL,
        transport: Any = None,
        request_timeout_seconds: float = 180.0,
        sleep: Callable[[float], None] = time.sleep,
    ) -> None:
        super().__init__(
            base_url=base_url,
            transport=transport,
            request_timeout_seconds=request_timeout_seconds,
            sleep=sleep,
        )
        self.model = model

    def _model(self, params: Mapping[str, object]) -> str:
        return str(params.get("model") or self.model)

    def generate(self, request: GenerationRequest, *, api_key: str) -> GenerationResult:
        import base64

        params = request.params
        model_id = self._model(params)
        body: dict[str, object] = {
            "model": model_id,
            "prompt": _prompt(params),
            "size": str(params.get("size") or "2K"),
            "response_format": "b64_json",
            "output_format": "jpeg",
            "watermark": False,
            "sequential_image_generation": "disabled",
        }
        images = _references(params.get("images"))
        if images:
            body["image"] = images[0] if len(images) == 1 else list(images)
        with self._client(api_key) as client:
            data = self._post(client, "/images/generations", body)
        items = [item for item in data.get("data") or () if isinstance(item, dict)]
        decoded = [base64.b64decode(item["b64_json"]) for item in items if item.get("b64_json")]
        if not decoded:
            # nothing came out: the error is at the top level, or per image (moderation)
            error = data.get("error") if isinstance(data.get("error"), dict) else None
            error = error or next(
                (item["error"] for item in items if isinstance(item.get("error"), dict)), None
            )
            if error:
                raise ArkAPIError(200, error.get("code"), error.get("message") or "")
            raise ArkError(f"Seedream returned no image: {data!r}")
        usage = data.get("usage") if isinstance(data.get("usage"), dict) else {}
        pieces = int(usage.get("generated_images") or len(decoded))
        return GenerationResult(
            payload={
                "images": decoded,
                "sizes": [item.get("size") for item in items if item.get("b64_json")],
                "references": len(images),
            },
            model_id=model_id,
            provider=self.name,
            usage=Usage(pieces=pieces, output_tokens=int(usage.get("output_tokens") or 0)),
            model_revision=str(data.get("model") or model_id),
        )

    def estimate_cost_usd(
        self,
        request: GenerationRequest,
        pricing: PricingTable,
        *,
        api_key: str | None = None,  # unused: per-piece pricing
    ) -> Decimal:
        _prompt(request.params)
        _references(request.params.get("images"))
        return pricing.unit_price(model_id=self._model(request.params), unit="per_piece")


def _references(value: object) -> tuple[str, ...]:
    if value is None:
        return ()
    if isinstance(value, str) or not isinstance(value, Sequence):
        raise ValueError("'images' must be a list of image URLs or data URLs")
    images = tuple(str(v) for v in value if v)
    if len(images) > MAX_REFERENCE_IMAGES:
        raise ValueError(
            f"{len(images)} reference images; Seedream takes at most {MAX_REFERENCE_IMAGES}"
        )
    return images
