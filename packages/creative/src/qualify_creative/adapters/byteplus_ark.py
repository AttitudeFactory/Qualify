@dataclass(frozen=True)
class _VideoSpec:
    """``request.params`` validated once, before any network call — a bad spec must fail
    the pre-flight, not cost a task."""

    model_id: str
    family: SeedanceFamily
    prompt: str
    first_frame: str | None
    last_frame: str | None
    #: `role: reference_image` / `reference_video` / `reference_audio`, in order — the
    #: prompt names them «Imagen 1», «Video 1», «Audio 1».
    reference_images: tuple[str, ...]
    reference_videos: tuple[str, ...]
    reference_audios: tuple[str, ...]
    ratio: str
    resolution: str
    seconds: int
    generate_audio: bool
    camera_fixed: bool | None
    return_last_frame: bool

    @classmethod
    def from_params(cls, params: Mapping[str, object], default_model: str) -> _VideoSpec:
        model_id = str(params.get("model") or default_model)
        family = seedance_family(model_id)
        prompt = _prompt(params)
        dialogue = params.get("dialogue")
        if isinstance(dialogue, str) and dialogue.strip() and family.audio:
            # 2.x speaks what is in double quotes (ModelArk's generate_audio guidance)
            line = dialogue.strip().replace('"', "'")
            prompt = _capped(f'{prompt}\nDice a cámara: "{line}"')
        first_frame = params.get("first_frame")
        if first_frame is not None and (not isinstance(first_frame, str) or not first_frame):
            raise ValueError("'first_frame' must be an image URL or a data URL")
        last_frame = params.get("last_frame")
        if last_frame is not None and (not isinstance(last_frame, str) or not last_frame):
            raise ValueError("'last_frame' must be an image URL or a data URL")
        if last_frame and not first_frame:
            raise ValueError("a 'last_frame' needs a 'first_frame'")
        if last_frame and not family.last_frame:
            raise ValueError(f"{model_id} takes no closing frame")
        images = _urls(params.get("reference_images"), "reference_images", data_ok=True)
        videos = _urls(params.get("reference_videos"), "reference_videos", data_ok=False)
        audios = _urls(params.get("reference_audios"), "reference_audios", data_ok=False)
        if images or videos or audios:
            if not family.references:
                raise ValueError(f"{model_id} takes no references: use a Seedance 2.x model")
            if first_frame or last_frame:
                # ModelArk: a reference task cannot carry the frame roles
                raise ValueError("references and first/last frame roles cannot be mixed")
            if len(images) > MAX_CLIP_REFERENCE_IMAGES:
                raise ValueError(f"at most {MAX_CLIP_REFERENCE_IMAGES} reference images")
            if len(videos) > MAX_REFERENCE_VIDEOS or len(audios) > MAX_REFERENCE_AUDIOS:
                raise ValueError(
                    f"at most {MAX_REFERENCE_VIDEOS} reference videos and "
                    f"{MAX_REFERENCE_AUDIOS} audio files"
                )
        ratio = str(params.get("ratio") or "9:16")
        if ratio not in RATIOS:
            raise ValueError(f"ratio must be one of {sorted(RATIOS)}, got {ratio!r}")
        resolution = str(params.get("resolution") or "720p")
        if resolution not in family.resolutions:
            raise ValueError(f"{model_id} renders {sorted(family.resolutions)}, not {resolution!r}")
        raw_seconds = params.get("duration_seconds", family.min_seconds)
        if isinstance(raw_seconds, bool) or not isinstance(raw_seconds, int):
            raise ValueError(f"duration_seconds must be an integer, got {raw_seconds!r}")
        # the brief's length is a wish; the model's range is a fact
        seconds = min(max(raw_seconds, family.min_seconds), family.max_seconds)
        audio = params.get("generate_audio", family.audio)
        camera_fixed = params.get("camera_fixed")
        return cls(
            model_id=model_id,
            family=family,
            prompt=prompt,
            first_frame=first_frame,
            last_frame=last_frame,
            reference_images=images,
            reference_videos=videos,
            reference_audios=audios,
            ratio=ratio,
            resolution=resolution,
            seconds=seconds,
            generate_audio=bool(audio) and family.audio,
            camera_fixed=bool(camera_fixed)
            if family.camera_fixed and camera_fixed is not None
            else None,
            return_last_frame=bool(params.get("return_last_frame", True)),
        )

    def body(self, wire_model: str) -> dict[str, object]:
        content: list[dict[str, object]] = [{"type": "text", "text": self.prompt}]
        if self.first_frame:
            content.append(
                {"type": "image_url", "image_url": {"url": self.first_frame}, "role": "first_frame"}
            )
        if self.last_frame:
            content.append(
                {"type": "image_url", "image_url": {"url": self.last_frame}, "role": "last_frame"}
            )
        for url in self.reference_images:
            content.append(
                {"type": "image_url", "image_url": {"url": url}, "role": "reference_image"}
            )
        for url in self.reference_videos:
            content.append(
                {"type": "video_url", "video_url": {"url": url}, "role": "reference_video"}
            )
        for url in self.reference_audios:
            content.append(
                {"type": "audio_url", "audio_url": {"url": url}, "role": "reference_audio"}
            )
        body: dict[str, object] = {
            "model": wire_model,
            "content": content,
            "ratio": self.ratio,
            "resolution": self.resolution,
            "duration": self.seconds,
            "watermark": False,
            "return_last_frame": self.return_last_frame,
        }
        if self.family.audio:
            body["generate_audio"] = self.generate_audio
        if self.camera_fixed is not None:
            body["camera_fixed"] = self.camera_fixed
        return body


class SeedanceVideoAdapter(_ArkClient):
    """``GenerationProvider`` for a generated scene video (`GenerationTask.SCENE_VIDEO`).

    ``request.params``:

    - ``prompt`` (required) — the scene and its action; ``first_frame`` — an image URL or
      a ``data:`` URL the video starts on (image-to-video), omitted = text-to-video;
      ``last_frame`` — the frame it ends on (needs ``first_frame``; 1.0 pro and 2.x);
    - ``reference_images`` / ``reference_videos`` / ``reference_audios`` — what a 2.x
      model follows (never mixed with the frames). Images may be ``data:`` URLs; videos
      and audio must be public ``https`` URLs — ModelArk takes no Base64 for them;
    - ``model`` (default: the adapter's), ``ratio`` (``9:16``…), ``resolution``
      (``480p``/``720p``/``1080p`` as the family allows), ``duration_seconds`` (clamped
      to the family's range);
    - ``dialogue`` — the script line: spoken (in double quotes) by the audio families,
      ignored by the silent 1.0 family; ``generate_audio``; ``camera_fixed`` (1.x).
    """

    name = "seedance"
    supports = frozenset({GenerationTask.SCENE_VIDEO})

    def __init__(
        self,
        *,
        model: str = DEFAULT_SEEDANCE_MODEL,
        base_url: str = BASE_URL,
        transport: Any = None,
        poll_interval_seconds: float = DEFAULT_POLL_INTERVAL_SECONDS,
        poll_timeout_seconds: float = DEFAULT_POLL_TIMEOUT_SECONDS,
        request_timeout_seconds: float = 60.0,
        sleep: Callable[[float], None] = time.sleep,
        monotonic: Callable[[], float] = time.monotonic,
        endpoints: Mapping[str, str] | None = None,
        allow_presets: bool = False,
    ) -> None:
        super().__init__(
            base_url=base_url,
            transport=transport,
            request_timeout_seconds=request_timeout_seconds,
            sleep=sleep,
            endpoints=endpoints,
            allow_presets=allow_presets,
        )
        seedance_family(model)  # an unknown default fails at wiring, not at first use
        self.model = model
        self._poll_interval = poll_interval_seconds
        self._poll_timeout = poll_timeout_seconds
        self._monotonic = monotonic

    def spec(self, params: Mapping[str, object]) -> _VideoSpec:
        return _VideoSpec.from_params(params, self.model)

    def generate(self, request: GenerationRequest, *, api_key: str) -> GenerationResult:
        spec = self.spec(request.params)
        wire_model = self.wire_model(spec.model_id)  # refuses a preset before connecting
        with self._client(api_key) as client:
            task_id = self._create(client, spec, wire_model)
            data = self._wait(client, task_id)
        content = data.get("content") if isinstance(data.get("content"), dict) else {}
        usage = data.get("usage") if isinstance(data.get("usage"), dict) else {}
        tokens = int(usage.get("completion_tokens") or 0)
        seconds = Decimal(str(data.get("duration") or spec.seconds))
        payload: dict[str, object] = {
            "task_id": task_id,
            "video_url": content.get("video_url"),
            "last_frame_url": content.get("last_frame_url"),
            "duration_seconds": str(seconds),
            "ratio": data.get("ratio") or spec.ratio,
            "resolution": data.get("resolution") or spec.resolution,
            "seed": data.get("seed"),
            "tokens": tokens,
            "generate_audio": spec.generate_audio,
        }
        return GenerationResult(
            payload=payload,
            model_id=spec.model_id,
            provider=self.name,
            usage=Usage(pieces=1, media_seconds=seconds, output_tokens=tokens),
            model_revision=str(data.get("model") or spec.model_id),
            media_url=content.get("video_url"),
            media_expires_at_seconds=MEDIA_URL_TTL_SECONDS,
        )

    def estimate_cost_usd(
        self,
        request: GenerationRequest,
        pricing: PricingTable,
        *,
        api_key: str | None = None,  # unused: the token formula needs no vendor call
    ) -> Decimal:
        """ModelArk's own token formula at the clamped length; an unpriced model or
        resolution raises from the table rather than estimating zero."""
        spec = self.spec(request.params)
        tokens = estimate_video_tokens(spec.model_id, spec.resolution, spec.ratio, spec.seconds)
        return video_cost_usd(pricing, spec.model_id, spec.resolution, tokens)

    def get_task(self, task_id: str, *, api_key: str) -> Mapping[str, Any]:
        """One task's current state — the recovery path after an `ArkTaskTimeout`."""
        # quoted whole: a pasted id with `/` or `..` must not move the keyed call elsewhere
        path = f"/contents/generations/tasks/{quote(task_id, safe='')}"
        with self._client(api_key) as client:
            return _body_or_raise(client.get(path))

    # -- internals ----------------------------------------------------------------------

    def _create(self, client: Any, spec: _VideoSpec, wire_model: str) -> str:
        body = self._post(client, "/contents/generations/tasks", spec.body(wire_model))
        task_id = body.get("id")
        if not task_id:
            raise ArkError(f"create response carried no task id: {body!r}")
        return str(task_id)

    def _wait(self, client: Any, task_id: str) -> Mapping[str, Any]:
        import httpx  # lazy, already loaded by _client

        started = self._monotonic()
        consecutive_errors = 0
        while True:
            data: Mapping[str, Any] | None
            try:
                data = _body_or_raise(client.get(f"/contents/generations/tasks/{task_id}"))
                consecutive_errors = 0
            except ArkAPIError as exc:
                if exc.status_code < 500 and exc.status_code != 429:
                    raise
                consecutive_errors += 1
                if consecutive_errors >= MAX_CONSECUTIVE_POLL_ERRORS:
                    raise
                data = None
            except httpx.TransportError:
                consecutive_errors += 1
                if consecutive_errors >= MAX_CONSECUTIVE_POLL_ERRORS:
                    raise
                data = None

            if data is not None:
                status = str(data.get("status") or "")
                if status == _TERMINAL_OK:
                    content = data.get("content")
                    if not isinstance(content, dict) or not content.get("video_url"):
                        raise ArkError(f"task {task_id} succeeded without a video_url")
                    return data
                if status in _TERMINAL_FAILED:
                    error = data.get("error") if isinstance(data.get("error"), dict) else {}
                    raise ArkTaskFailed(task_id, status, error.get("code"), error.get("message"))

            waited = self._monotonic() - started
            if waited + self._poll_interval > self._poll_timeout:
                raise ArkTaskTimeout(task_id, waited)
            self._sleep(self._poll_interval)


