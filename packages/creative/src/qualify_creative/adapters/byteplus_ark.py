"""BytePlus ModelArk adapters — Seedance (video) and Seedream (image) behind the
``GenerationProvider`` seam (§ request 2026-10-07: the generator's videos move from HeyGen
to Seedance, and the advertising image is generated by Seedream).

API facts pinned from docs.byteplus.com (ModelArk, read 2026-10-07), and verified live
the same day with one Seedream 5.0 lite image and one Seedance 1.0 pro clip:

- One API key for both (``Authorization: Bearer``), one regional base URL
  (``https://ark.ap-southeast.bytepluses.com/api/v3``).
- **Video** is asynchronous: ``POST /contents/generations/tasks`` answers ``{"id"}``;
  ``GET /contents/generations/tasks/{id}`` walks ``queued``/``running`` to ``succeeded``,
  ``failed``, ``cancelled`` or ``expired``. ``content.video_url`` (and
  ``content.last_frame_url`` with ``return_last_frame``) is valid for 24 h — the caller
  copies the file at once. ``usage.completion_tokens`` is what is billed.
- **Image** is synchronous: ``POST /images/generations``; ``response_format=b64_json``
  returns the bytes in the body, so nothing depends on the 24 h URL.
- Errors are ``{"error": {"code", "message"}}``. A failed or moderated generation is not
  billed.
- **Model capabilities differ by family** (`SEEDANCE_FAMILIES`): Seedance 1.0 makes SILENT
  video, 2–12 s, and takes ``camera_fixed``/``seed``; the 2.x family generates audio — a
  line in double quotes in the prompt is spoken with lip-sync, and the prompt may be in
  Spanish — and refuses real human faces as reference images (a face Seedream generated
  is fine as a first frame of 1.x; 2.x has its own portrait rules).
- Billing: video by tokens, ``width × height × 24 fps × seconds / 1024`` at the output
  size; image per generated piece. A video task with reference videos is billed at a
  lower «with video input» rate, and its tokens include the input video (measured
  2026-10-23, `estimate_video_tokens`).

Seedance's task is two public steps (m-24852159, ADR 41 phase 1): ``submit`` sends it and
returns the vendor task id at once, ``poll`` reads its state once; a queue worker sends,
lets go of the thread and polls later. ``generate`` — what the synchronous Protocol and the
``InlineDispatcher`` thread call — is the composition of the two, unchanged for its
callers. Seedream answers inside ``generate`` (an image is synchronous).
"""

