class _ArkClient:
    def __init__(
        self,
        *,
        base_url: str,
        transport: Any,
        request_timeout_seconds: float,
        sleep: Callable[[float], None] = time.sleep,
    ) -> None:
        self._base_url = base_url.rstrip("/")
        self._transport = transport
        self._request_timeout = request_timeout_seconds
        self._sleep = sleep

    def _post(self, client: Any, path: str, body: Mapping[str, object]) -> Mapping[str, Any]:
        """POST `body` and return the JSON, sent again (up to `MAX_POST_ATTEMPTS`) only
        on the failures where the vendor never started the work — see
        `MAX_POST_ATTEMPTS` for why that keeps a retry from billing twice."""
        import httpx  # lazy, already loaded by _client

        for attempt in range(1, MAX_POST_ATTEMPTS + 1):
            try:
                return _body_or_raise(client.post(path, json=body))
            except (httpx.ConnectError, httpx.RemoteProtocolError):
                if attempt == MAX_POST_ATTEMPTS:
                    raise
            except ArkAPIError as exc:
                if exc.status_code not in POST_RETRY_STATUSES or attempt == MAX_POST_ATTEMPTS:
                    raise
            self._sleep(POST_RETRY_BACKOFF_SECONDS * attempt)
        raise AssertionError("unreachable")  # the loop returns or raises

    def _client(self, api_key: str) -> Any:
        """``httpx`` is imported lazily (the ``video`` extra), and the client is built with
        the resolved key only — never an ambient one."""
        if not api_key:
            raise ValueError("ModelArk adapter requires an explicit, non-empty api_key")
        import httpx  # lazy: optional dependency

        return httpx.Client(
            base_url=self._base_url,
            headers={"Authorization": f"Bearer {api_key}", "Content-Type": "application/json"},
            timeout=self._request_timeout,
            transport=self._transport,
        )


def _body_or_raise(response: Any) -> Mapping[str, Any]:
    try:
        body = response.json()
    except ValueError:
        body = {}
    body = body if isinstance(body, dict) else {}
    if response.status_code >= 400:
        error = body.get("error") if isinstance(body.get("error"), dict) else {}
        raise ArkAPIError(
            response.status_code,
            error.get("code"),
            error.get("message") or response.text[:300],
        )
    return body


def _prompt(params: Mapping[str, object]) -> str:
    prompt = params.get("prompt")
    if not isinstance(prompt, str) or not prompt.strip():
        raise ValueError("a ModelArk generation needs a non-empty 'prompt'")
    return _capped(prompt.strip())


def _urls(value: object, name: str, *, data_ok: bool) -> tuple[str, ...]:
    """A list of reference URLs, validated: ``data:`` only where ModelArk takes Base64
    (images), ``https`` otherwise."""
    if value is None:
        return ()
    if not isinstance(value, list | tuple) or not all(isinstance(v, str) and v for v in value):
        raise ValueError(f"'{name}' must be a list of URLs")
    for url in value:
        if url.startswith("data:"):
            if not data_ok:
                raise ValueError(f"'{name}' must be public https URLs, not data URLs")
        elif not url.startswith("https://"):
            raise ValueError(f"'{name}' must be https URLs")
    return tuple(value)


def _capped(prompt: str) -> str:
    """The vendor's hard cap, checked on what is actually sent — after the dialogue line
    a video prompt gains (PR #100 review), not only on the operator's part."""
    if len(prompt) > MAX_PROMPT_CHARS:
        raise ValueError(f"prompt is {len(prompt)} characters; the cap is {MAX_PROMPT_CHARS}")
    return prompt


