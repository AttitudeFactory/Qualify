# -- the scene's budget is not charged twice for what was already spent (defect 9) ----


def test_the_scene_budget_counts_earlier_spend_once() -> None:
    # 0.20 cap, 0.10 already spent in this piece, a 0.05 render: 0.05 is left for a 0.035
    # scene. Counting the earlier 0.10 twice would leave -0.05 and refuse the scene.
    seedream, remotion = FakeSeedream(), FakeRemotion()
    store = _store()
    producer = _producer(store, seedream, remotion, RenderPricedAt(Decimal("0.05")))
    draft_id = uuid4()
    usage = [
        MediaUsage(provider="x", model_id="y", unit="piece", quantity=1, cost_usd=Decimal("0.10"))
    ]
    outcome = producer._template(  # earlier spend in a piece is only reachable from inside
        TENANT_ID,
        draft_id,
        _brief(
            ContentKind.TEMPLATE,
            scene_prompt="sobre una roca",
            template_id="promo_producto",
            template_version=2,
        ),
        _kit(),
        COPY,
        BudgetContext(remaining_usd=Decimal("0.20")),
        usage,
        _Saver(store, TENANT_ID, draft_id, 1),
        [],
    )
    assert outcome.failure is None, outcome.detail
    assert len(seedream.requests) == 1 and len(remotion.requests) == 1
