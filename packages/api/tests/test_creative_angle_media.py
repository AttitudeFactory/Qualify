# -- a price is printed whole or not at all, and says so (defect 15) ------------------

#: Too long for the flyer pill even at its legible floor, and for the template's slot.
TOO_LONG = "Desde $ 12.499.900 COP por unidad"


def test_a_price_too_long_for_the_ad_image_is_left_out_with_a_warning() -> None:
    seedream, remotion = FakeSeedream(), FakeRemotion()
    store = _store()
    producer = _producer(store, seedream, remotion)
    long_price = _template(
        producer,
        _brief(ContentKind.STATIC_FLYER, scene_prompt="sobre una roca", price_line=TOO_LONG),
    )
    no_price = _template(producer, _brief(ContentKind.STATIC_FLYER, scene_prompt="sobre una roca"))
    assert long_price.failure is None and no_price.failure is None
    (warning,) = long_price.warnings
    assert warning.code == PRICE_NOT_PRINTED
    assert warning.fields["price"] == TOO_LONG and warning.fields["reason"] == "too_long"
    assert warning.detail  # the operator's words, for the UI block
    # nothing cut was printed: the piece is exactly the one without a price
    assert store.files[long_price.media[0].object_key] == store.files[no_price.media[0].object_key]
    assert no_price.warnings == ()


def test_a_price_too_long_for_the_template_slot_is_not_sent_and_is_warned() -> None:
    seedream, remotion = FakeSeedream(), FakeRemotion()
    outcome = _template(
        _producer(_store(), seedream, remotion),
        _brief(
            ContentKind.TEMPLATE,
            price_line=TOO_LONG,
            template_id="promo_producto",
            template_version=2,
        ),
    )
    assert outcome.failure is None, outcome.detail
    (render,) = remotion.requests
    assert "price_line" not in render.params["props"].texts  # never a shortened figure
    (warning,) = outcome.warnings
    assert warning.code == PRICE_NOT_PRINTED
    assert warning.fields["reason"] == "too_long" and warning.fields["max_chars"] == 24


def test_the_template_price_rule() -> None:
    manifest = TemplateRegistry.from_dir(TEMPLATES).get("promo_producto", 2)
    no_slot = manifest.model_copy(
        update={"inputs": {k: v for k, v in manifest.inputs.items() if k != "price_line"}}
    )
    draft_id = uuid4()
    warnings: list[Any] = []
    # no catalog price on the brief: the template resolves its own, as before
    assert _template_price(draft_id, manifest, _brief(ContentKind.TEMPLATE), warnings) is None
    priced = _brief(ContentKind.TEMPLATE, price_line="$18.000")
    assert _template_price(draft_id, manifest, priced, warnings) == "$18.000"
    assert warnings == []
    # a template without a price slot prints none — "" so no fallback price sneaks in
    assert _template_price(draft_id, no_slot, priced, warnings) == ""
    assert [w.fields["reason"] for w in warnings] == ["no_price_slot"]


