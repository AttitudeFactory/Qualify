def test_the_router_counts_the_scene_as_the_photo_a_template_needs() -> None:
    # promo_producto needs two photos: one upload alone is refused for free...
    seedream, remotion = FakeSeedream(), FakeRemotion()
    alone = _template(
        _producer(_store(), seedream, remotion), _brief(ContentKind.TEMPLATE, photos=1)
    )
    assert alone.failure == FailureReason.ROUTE_BLOCKED_BY_POLICY.value
    assert seedream.requests == [] and remotion.requests == []
    # ...and the same upload plus the angle's scene is chosen, the scene leading
    outcome = _template(
        _producer(_store(), seedream, remotion),
        _brief(ContentKind.TEMPLATE, photos=1, scene_prompt="sobre una roca"),
    )
    assert outcome.failure is None, outcome.detail
    assert len(seedream.requests) == 1
    (render,) = remotion.requests
    photos = render.params["props"].photos
    assert len(photos) == 2 and "scene.jpg" in photos[0]
    assert all("pending/" not in p for p in photos)


def test_a_budget_for_the_scene_but_not_the_render_pays_nothing() -> None:
    seedream, remotion = FakeSeedream(), FakeRemotion()
    brief = _brief(
        ContentKind.TEMPLATE,
        scene_prompt="sobre una roca",
        template_id="promo_producto",
        template_version=2,
    )
    producer = _producer(_store(), seedream, remotion, RenderPricedAt(Decimal("1.00")))
    # the scene (0.035) fits 1.02, the scene plus the render (1.035) does not
    outcome = _template(producer, brief, budget=BudgetContext(remaining_usd=Decimal("1.02")))
    assert outcome.failure == FailureReason.BUDGET_EXCEEDED.value
    assert seedream.requests == [] and remotion.requests == []
    assert outcome.usage == ()
    assert outcome.template_run is not None and outcome.template_run.status == "failed"
    # with room for both, both are paid, in order
    paid = _template(producer, brief, budget=BudgetContext(remaining_usd=Decimal("1.10")))
    assert paid.failure is None, paid.detail
    assert [u.provider for u in paid.usage] == ["seedream", "remotion"]


