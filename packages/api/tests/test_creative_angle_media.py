"""`MediaProducer` for the «10 variaciones» briefs (ticket 24803289), without the network:
the catalog's `price_line` reaches the composed flyer and the advertising image, and a
template brief with a scene gets that scene generated by Seedream and prepended to the
template's photos (the render request shows it first, the cost is recorded)."""

