#!/usr/bin/env python3
"""Generate Codex adapters from portable role skills (Python standard library).

Run `python3 infra/agents/sync.py` after editing a role, or add `--check` to
detect adapter drift without writing. Role frontmatter uses one JSON value per
YAML field (JSON is a YAML subset) so generation needs no third-party parser.
"""

from __future__ import annotations

import argparse
import json
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
SKILLS = ROOT / ".agents/skills"


def adapters() -> dict[Path, str]:
    """Validate portable roles and render Codex entry points without touching Claude files."""
    outputs = {}
    for source in sorted(SKILLS.glob("*/SKILL.md")):
        _, header, _ = source.read_text(encoding="utf-8").split("---", 2)
        # Other project/vendor skills can use the full YAML syntax.
        if '"claude-model"' not in header:
            continue
        meta = {
            key: json.loads(value)
            for key, value in (line.split(":", 1) for line in header.strip().splitlines())
        }
        name = meta["name"]
        if name != source.parent.name:
            raise ValueError(f"Role name does not match directory: {source}")
        options = meta["metadata"]
        required = options["required-skills"].split(",")
        for dependency in required:
            if not (SKILLS / dependency / "SKILL.md").is_file():
                raise ValueError(f"{name}: missing required skill {dependency}")
        description = json.dumps(meta["description"], ensure_ascii=False)
        entry = f".agents/skills/{name}/SKILL.md"
        instructions = (
            f"Read AGENTS.md, then {entry}, and load the required skills listed there "
            "before working. Follow that role's ownership, constraints and deliverables. "
            "Resolve repository paths from the project root. "
            "Use the active client's available tools and inherited model/provider settings. "
            "Report missing capabilities; do not claim tools or reviews were run when they were not."
        )
        codex = (
            "# Generated by infra/agents/sync.py; edit the portable role skill.\n"
            f"name = {json.dumps(name)}\n"
            f"description = {description}\n"
            f"developer_instructions = {json.dumps(instructions, ensure_ascii=False)}\n"
        )
        outputs[ROOT / ".codex/agents" / f"{name}.toml"] = codex

    if not outputs:
        raise ValueError("No portable roles found")
    return outputs


def main() -> int:
    """Write Codex adapters or report stale/missing adapters."""
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    stale = []
    for path, content in adapters().items():
        if path.is_file() and path.read_text(encoding="utf-8") == content:
            continue
        stale.append(str(path.relative_to(ROOT)))
        if not args.check:
            path.parent.mkdir(parents=True, exist_ok=True)
            path.write_text(content, encoding="utf-8")
    if args.check and stale:
        print("Stale or missing Codex adapters:\n" + "\n".join(stale))
        return 1
    print(f"{'Checked' if args.check else 'Synced'} portable roles and Codex adapters.")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
